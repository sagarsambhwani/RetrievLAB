"""
Experiment 003

Question:
Does the Embedder correctly generate embeddings for Markdown chunks using the FastEmbed model?

Expected Result:
- Each chunk should have an embedding vector generated by the FastEmbed model.
- The embedding vectors should be of the expected dimensionality (e.g., 384).

"""

from pathlib import Path

from retrievlab.ingestion.loader import DocumentLoader
from retrievlab.chunking.markdown import MarkdownChunker
from retrievlab.embeddings.embedder import Embedder
from retrievlab.embeddings.fastembed import FastEmbedClient
loader = DocumentLoader()
chunker = MarkdownChunker()
embedder = Embedder(client=FastEmbedClient())

documents = loader.load(Path("data/raw/"))
chunks = chunker.chunk(documents[0])  # Chunk the first document for demonstration

print(f"\nLoaded {len(documents)} documents")
print(f"Chunked into {len(chunks)} chunks\n")

for document in documents:
    chunks = chunker.chunk(document)
    chunks = embedder.embed(chunks)

    print(f"\n{'=' * 80}")
    print(f"Document: {document.title}")
    print(f"Produced {len(chunks)} chunks")

    for i, chunk in enumerate(chunks, start=1):
        print(f"\nChunk {i}")
        print(f"Chunk ID: {chunk.id}")
        print(f"Heading: {chunk.metadata['heading']}")
        print(chunk.text, chunk.embedding[:5])  # Print first 5 dimensions of the embedding vector
